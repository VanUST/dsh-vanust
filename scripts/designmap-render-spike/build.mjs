/**
 * Build the spike:
 *  1. seed.js  → vendor/seed.js  (react/react-dom bundled once, exposes the
 *                module-table seed: the spike's stand-in for the DSH shell table)
 *  2. panel.jsx → CJS body → bundle/client.js, wrapped in the harness client
 *                module registration `window.__ModuleLoader__.load({id,factory})`
 *  3. the negative control: the same panel with @xyflow/react EXTERNAL, to
 *                observe what a bare `import '@xyflow/react'` does at runtime
 *  4. vendor the real @deepseek-ai/dsh-client-modules/client.js from the
 *                installed dsh so the page runs the real loader, not a mock
 */
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { gzipSync } from 'node:zlib'
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, 'public')
const PKG = '@spike/designmap-render'
const DSH_MODULES_CLIENT = '/home/iustimov/.npm/node/lib/node_modules/@deepseek-ai/dsh/node_modules/@deepseek-ai/dsh-client-modules/lib/client.js'

const EXTERNAL = ['react', 'react-dom', 'react-dom/client', 'react/jsx-runtime']

const bytes = (text) => Buffer.byteLength(text)
const kb = (n) => `${(n / 1024).toFixed(1)} KiB`

async function buildSeed() {
  const result = await build({
    entryPoints: [join(HERE, 'src/seed.js')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome120'],
    write: false,
    minify: false,
    legalComments: 'none',
    define: { 'process.env.NODE_ENV': '"production"' },
  })
  const text = result.outputFiles[0].text
  await writeFile(join(OUT, 'seed.js'), text)
  return bytes(text)
}

async function buildClient({ entry, outfile, external }) {
  const result = await build({
    entryPoints: [join(HERE, entry)],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    external,
    loader: { '.css': 'text', '.js': 'jsx' },
    jsx: 'automatic',
    jsxImportSource: 'react',
    write: false,
    minify: false,
    legalComments: 'none',
    define: { 'process.env.NODE_ENV': '"production"' },
  })
  const body = result.outputFiles[0].text
  const wrapped = `/* ${PKG} — generated by build.mjs; do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PKG)},
  factory(require) {
${body}
  },
});
`
  await writeFile(join(OUT, outfile), wrapped)
  return { body: bytes(body), wrapped: bytes(wrapped) }
}

async function main() {
  await mkdir(join(OUT, 'bundle'), { recursive: true })
  await mkdir(join(OUT, 'vendor'), { recursive: true })

  const bundled = await buildClient({ entry: 'src/panel.jsx', outfile: 'bundle/client.js', external: EXTERNAL })
  const bare = await buildClient({
    entry: 'src/panel.jsx',
    outfile: 'bundle/client.bare.js',
    external: [...EXTERNAL, '@xyflow/react'],
  })
  const seed = await buildSeed()

  const modulesSource = await readFile(DSH_MODULES_CLIENT)
  await copyFile(DSH_MODULES_CLIENT, join(OUT, 'vendor/dsh-client-modules.client.js'))
  const minified = await build({
    entryPoints: [join(HERE, 'src/panel.jsx')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    external: EXTERNAL,
    loader: { '.css': 'text', '.js': 'jsx' },
    jsx: 'automatic',
    jsxImportSource: 'react',
    write: false,
    minify: true,
    legalComments: 'none',
    define: { 'process.env.NODE_ENV': '"production"' },
  })
  const minifiedBytes = Buffer.byteLength(minified.outputFiles[0].text)
  const gzipBytes = gzipSync(minified.outputFiles[0].text).byteLength
  const modulesHash = createHash('sha256').update(modulesSource).digest('hex')
  const modulesStat = await stat(DSH_MODULES_CLIENT)

  const manifest = {
    builtAt: new Date().toISOString(),
    esbuild: (await import('esbuild/package.json', { with: { type: 'json' } })).default.version,
    xyflow: (await import('@xyflow/react/package.json', { with: { type: 'json' } })).default.version,
    react: (await import('react/package.json', { with: { type: 'json' } })).default.version,
    external: EXTERNAL,
    sizes: {
      panelCjs: bundled.body,
      clientBundle: bundled.wrapped,
      bareClientBundle: bare.wrapped,
      clientBundleMinified: minifiedBytes,
      clientBundleMinifiedGzip: gzipBytes,
      seedBundle: seed,
      dshClientModules: modulesSource.byteLength,
    },
    vendoredDshClientModules: {
      path: DSH_MODULES_CLIENT,
      sha256: modulesHash,
      mtime: modulesStat.mtime.toISOString(),
    },
  }
  await writeFile(join(OUT, 'build-manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

  console.log('esbuild', manifest.esbuild)
  console.log('@xyflow/react', manifest.xyflow, '· react', manifest.react)
  console.log('client.js      ', kb(bundled.wrapped), '(CJS body', kb(bundled.body) + ')')
  console.log('client.bare.js ', kb(bare.wrapped), '(negative control: @xyflow/react external)')
  console.log('minified       ', kb(minifiedBytes), '· gzip', kb(gzipBytes))
  console.log('seed.js        ', kb(seed))
  console.log('dsh client-mod ', kb(modulesSource.byteLength), 'sha256', modulesHash.slice(0, 16) + '…')
}

await main()
