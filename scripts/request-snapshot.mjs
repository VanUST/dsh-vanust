function harnessBin() {
  const candidates = [
    process.env.DSH_HARNESS_BIN,
    join(dirname(process.execPath), 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js'),
    join(process.env.APPDATA ?? '', 'npm', 'node_modules', '@deepseek-ai', 'dsh', 'lib', 'bin.js'),
  ].filter((path) => typeof path === 'string' && path !== '')
  const found = candidates.find((path) => existsSync(path))
  if (found === undefined) throw new Error('the installed @deepseek-ai/dsh was not found; set DSH_HARNESS_BIN to its lib/bin.js')
  return found
}

function prepare() {
  mkdirSync(TMP, { recursive: true })
  writeFileSync(PRELOAD, PRELOAD_SOURCE)
  mkdirSync(WORKDIR, { recursive: true })
  const source = join(homedir(), '.dsh', 'profiles', 'headless')
  if (!existsSync(source)) throw new Error('no headless profile at ' + source)
  if (!existsSync(PROFILE)) {
    mkdirSync(join(HOME, 'profiles'), { recursive: true })
    cpSync(source, PROFILE, { recursive: true })
  }
  const modules = join(HOME, 'profiles', 'node_modules')
  if (!existsSync(modules)) symlinkSync(join(homedir(), '.dsh', 'profiles', 'node_modules'), modules, 'junction')
}

function capture(name, prompt, pin) {
  const dir = join(TMP, name)
  rmSync(dir, { recursive: true, force: true })
  mkdirSync(dir, { recursive: true })
  const result = spawnSync(process.execPath, ['--import', pathToFileURL(PRELOAD).href, harnessBin(), 'headless', prompt], {
    cwd: WORKDIR,
    encoding: 'utf8',
    timeout: 120000,
    env: {
      ...process.env,
      DSH_HOME: HOME,
      SNAPSHOT_DIR: dir,
      SNAPSHOT_PIN: pin ? '1' : '0',
      DEEPSEEK_API_KEY: process.env.DEEPSEEK_API_KEY ?? 'stub-not-a-key',
    },
  })
  const files = readdirSync(dir).filter((file) => file.endsWith('.json')).sort()
  const bodies = files.map((file) => {
    const call = JSON.parse(readFileSync(join(dir, file), 'utf8'))
    return { file, url: call.url, body: call.body }
  })
  let step = null
  for (const entry of bodies) if (step === null || entry.body.length > step.body.length) step = entry
  if (step === null) throw new Error('no POST was captured for ' + name + '; exit ' + result.status + '\n' + result.stderr)
  return { name, dir, prompt, exit: result.status, stderr: result.stderr, step, calls: bodies.length }
}

/** Positions of the top-level keys of a serialized JSON object, so a byte offset names a field. */
function fieldOffsets(text) {
  const offsets = []
  let depth = 0
  let inString = false
  let escaped = false
  let expectKey = false
  let keyStart = -1
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index]
    if (inString) {
      if (escaped) escaped = false
      else if (char === '\\') escaped = true
      else if (char === '"') {
        inString = false
        if (expectKey) {
          offsets.push({ key: text.slice(keyStart + 1, index), offset: keyStart })
          expectKey = false
        }
      }
      continue
    }
    if (char === '"') { inString = true; keyStart = index; continue }
    if (char === '{' || char === '[') { depth += 1; expectKey = depth === 1 && char === '{'; continue }
    if (char === '}' || char === ']') { depth -= 1; continue }
    if (char === ',' && depth === 1) expectKey = true
  }
  return offsets
}

function firstDifference(left, right) {
  const limit = Math.min(left.length, right.length)
  for (let index = 0; index < limit; index += 1) {
    if (left[index] !== right[index]) {
      return { offset: index, left: left.slice(Math.max(0, index - 40), index + 40), right: right.slice(Math.max(0, index - 40), index + 40) }
    }
  }
  if (left.length === right.length) return null
  return { offset: limit, left: left.slice(Math.max(0, limit - 40)), right: right.slice(Math.max(0, limit - 40)) }
}

function fieldAt(offsets, offset) {
  let named = 'body'
  for (const entry of offsets) if (entry.offset <= offset) named = entry.key
  return named
}

/** Every generated identifier replaced by one placeholder, so only real content compares. */
const normalise = (text) => text.replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/g, '<uuid>')

function analyse(run) {
  const text = run.step.body
  const body = JSON.parse(text)
  const offsets = fieldOffsets(text)
  const systemText = typeof body.system === 'string' ? body.system : JSON.stringify(body.system)
  const blocks = systemText.split(/\n\n+/).filter((block) => block.trim() !== '')
  const messages = (body.messages ?? []).map((message) => ({
    role: message.role,
    blocks: (message.content ?? []).map((block) => ({
      type: block.type,
      bytes: (block.text ?? JSON.stringify(block)).length,
      sha256: sha256(block.text ?? JSON.stringify(block)),
      head: (block.text ?? JSON.stringify(block)).slice(0, 80).replace(/\n/g, ' '),
      text: block.text ?? null,
    })),
  }))
  return {
    scenario: run.name,
    prompt: run.prompt,
    exit: run.exit,
    posts: run.calls,
    url: run.step.url,
    bodyBytes: Buffer.byteLength(text, 'utf8'),
    bodySha256: sha256(text),
    identityNormalizedSha256: sha256(normalise(text)),
    fields: offsets.map((entry) => entry.key),
    system: {
      bytes: Buffer.byteLength(systemText, 'utf8'),
      sha256: sha256(systemText),
      blocks: blocks.map((block, index) => ({ index, bytes: Buffer.byteLength(block, 'utf8'), sha256: sha256(block), head: block.split('\n')[0].slice(0, 80) })),
    },
    tools: (body.tools ?? []).map((tool) => ({ name: tool.name, bytes: JSON.stringify(tool).length, sha256: sha256(JSON.stringify(tool)), schema: tool })),
    executionContext: messages[0]?.blocks.slice(1) ?? [],
    messages,
    hasSessionLog: body.dsh_session_log !== undefined,
  }
}

const prompt = 'Reply with ok'
const changedPrompt = 'Reply with ok, briefly'
prepare()
const runs = [capture('a1', prompt, true), capture('a2', prompt, true), capture('b', changedPrompt, true)]
const report = runs.map(analyse)
const repeat = firstDifference(runs[0].step.body, runs[1].step.body)
const repeatNormalised = firstDifference(normalise(runs[0].step.body), normalise(runs[1].step.body))
const repeatSection = repeat === null ? null : fieldAt(fieldOffsets(runs[0].step.body), repeat.offset)
const changed = firstDifference(runs[0].step.body, runs[2].step.body)
const changedSection = changed === null ? null : fieldAt(fieldOffsets(runs[0].step.body), changed.offset)
